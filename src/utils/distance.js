/*
  Haversine Distance
  -------------------
  Calculates the STRAIGHT-LINE distance (in km) between two points on Earth
  given their latitude and longitude in degrees. This is NOT driving distance
  (that would need a paid routing API), but good enough for a "nearby" filter.

  Formula explanation for viva:
  1. Convert degrees to radians (trigonometry functions use radians, not degrees)
  2. a = sin²(Δφ/2) + cos(φ1) * cos(φ2) * sin²(Δλ/2)
  3. c = 2 * atan2(√a, √(1−a))
  4. d = R * c    where R = 6371 km (earth radius)
*/
export function haversineDistance(lat1, lon1, lat2, lon2) {
  if (lat1 == null || lon1 == null || lat2 == null || lon2 == null) return null;
  const R = 6371; // Earth radius in km
  const toRad = (deg) => (deg * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRad(lat1)) *
      Math.cos(toRad(lat2)) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const d = R * c;
  return Math.round(d * 10) / 10; // round to 1 decimal place
}

