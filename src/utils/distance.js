export function coordsForPincode(pincode) {
  if (!pincode) return null;
  const key = String(pincode).trim();
  const entry = PINCODE_COORDS[key];
  if (entry) return { latitude: entry[0], longitude: entry[1] };
  if (/^4\d{5}$/.test(key)) {
    return { latitude: 19.0760, longitude: 72.8777 };
  }
  return null;
}

export function hasValidCoords(lat, lng) {
  if (lat == null || lng == null) return false;
  if (typeof lat !== 'number' || typeof lng !== 'number') return false;
  if (isNaN(lat) || isNaN(lng)) return false;
  if (lat === 0 && lng === 0) return false;
  if (lat < -90 || lat > 90) return false;
  if (lng < -180 || lng > 180) return false;
  return true;
}

export function resolveEntityCoords(entity) {
  if (!entity) return { latitude: null, longitude: null };
  if (hasValidCoords(entity.latitude, entity.longitude)) {
    return { latitude: entity.latitude, longitude: entity.longitude };
  }
  const pincodeCoords = coordsForPincode(entity.pincode);
  if (pincodeCoords) return pincodeCoords;
  return { latitude: entity.latitude || null, longitude: entity.longitude || null };
}

/*
  Pincode Proximity Check
  ------------------------
  Two pincodes are considered "in the same area/city" if their first N digits match.
  This is used as an ADDITIONAL safety layer on top of distance, to ensure a
  restaurant in Mumbai (400xxx) never matches an NGO in Delhi (110xxx) even if
  some coordinates accidentally overlap.

  By default (prefixDigits=3):
    400008 (Mumbai Central)  ~  400007 (Grant Road)   => MATCH (Mumbai)
    400008 (Mumbai)          ~  110001 (Delhi)        => NO MATCH (cross-city)
*/
export function pincodesNearby(pinA, pinB, prefixDigits = 3) {
  if (!pinA || !pinB) return true; // no pincode info => fall back to distance only
  const a = String(pinA).trim().slice(0, prefixDigits);
  const b = String(pinB).trim().slice(0, prefixDigits);
  if (a.length < prefixDigits || b.length < prefixDigits) return true;
  return a === b;
}

/*
  Estimate Delivery ETA (front-end preview, server also recalculates authoritatively)
  -------------------------------------------------------------------------------------
  Mirrors the server model so the UI can show a quick estimate before the agent
  actually clicks "Start Journey" (the server always recalculates with its own data
  when start-journey is called).
*/
export function estimateDeliveryMinutes(distAgentRestKm, distRestNgoKm, vehicleType) {
  const speeds = { Bike: 20, Scooter: 25, Car: 30, Walk: 5 };
  const v = speeds[(vehicleType || 'Bike')] || 22;
  const totalDist = Math.max(0, Number(distAgentRestKm) || 0) + Math.max(0, Number(distRestNgoKm) || 0);
  const travelMin = (totalDist / v) * 60;
  const trafficFactor = 1.4;
  const bufferMin = 10 + 5; // pickup + handover
  return Math.round(travelMin * trafficFactor + bufferMin);
}
